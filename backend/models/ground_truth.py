"""
Ground Truth Validation history model for auditability and dataset quality gates.
Enforces strict immutability and provenance tracking: verdicts generated by the
deterministic rule engine cannot be overwritten, modified, or deleted.
"""

from datetime import datetime, timezone
import json
from typing import Optional
from sqlalchemy import Boolean, Column, DateTime, Integer, String, Text, event
from backend.database import Base


class GroundTruthValidation(Base):
    __tablename__ = "ground_truth_validations"

    id = Column(Integer, primary_key=True, index=True, autoincrement=True)
    dataset_name = Column(String(255), nullable=False, index=True)
    total_samples = Column(Integer, nullable=False)
    valid_samples = Column(Integer, nullable=False)
    invalid_samples = Column(Integer, nullable=False)
    is_valid = Column(Boolean, nullable=False, default=True)
    issues = Column(Text, nullable=True)  # JSON-encoded list of issues
    statistics = Column(Text, nullable=True)  # JSON-encoded statistics

    # Provenance and immutability attributes
    verdict_hash = Column(String(64), nullable=True, index=True)
    rule_engine_version = Column(String(50), default="vijay_rule_engine_v1.0", nullable=False)
    run_sequence = Column(Integer, default=1, nullable=False)
    conflict_detected = Column(Boolean, default=False, nullable=False)
    conflict_details = Column(Text, nullable=True)

    created_at = Column(
        DateTime,
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
    )

    def get_issues_list(self) -> list:
        if self.issues:
            try:
                return json.loads(self.issues)
            except Exception:
                return []
        return []

    def get_statistics_dict(self) -> Optional[dict]:
        if self.statistics:
            try:
                return json.loads(self.statistics)
            except Exception:
                return None
        return None

    def get_conflict_details_dict(self) -> Optional[dict]:
        if self.conflict_details:
            try:
                return json.loads(self.conflict_details)
            except Exception:
                return None
        return None


# ─────────────────────────────────────────────────────────────────────────────
# SQLAlchemy Engine-Level Immutability Enforcement
# ─────────────────────────────────────────────────────────────────────────────

@event.listens_for(GroundTruthValidation, "before_update")
def enforce_ground_truth_immutability_on_update(mapper, connection, target):
    """Guarantees ground-truth verdicts cannot be silently or explicitly overwritten."""
    raise PermissionError(
        f"IMMUTABILITY VIOLATION: GroundTruthValidation records are immutable (record id={target.id}). "
        "Ground-truth verdicts cannot be modified. New evaluations must be appended as historical runs."
    )


@event.listens_for(GroundTruthValidation, "before_delete")
def enforce_ground_truth_immutability_on_delete(mapper, connection, target):
    """Guarantees ground-truth records cannot be deleted."""
    raise PermissionError(
        f"IMMUTABILITY VIOLATION: GroundTruthValidation records are immutable (record id={target.id}). "
        "Ground-truth records cannot be deleted."
    )
